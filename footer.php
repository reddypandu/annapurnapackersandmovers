<script>
    // Mobile Navigation Toggle
    const menuToggle = document.getElementById('menuToggle');
    const navMenu = document.getElementById('navMenu');
    if (menuToggle && navMenu) {
        menuToggle.addEventListener('click', () => {
            const isOpen = navMenu.classList.toggle('is-open');
            menuToggle.setAttribute('aria-expanded', isOpen);
        });
    }

    // Quote Modal Controls
    function openQuoteModal() {
        const modal = document.getElementById('quoteModal');
        if (modal) {
            modal.classList.add('active');
            document.body.style.overflow = 'hidden';
            const firstInput = modal.querySelector('input');
            if (firstInput) firstInput.focus();
        }
    }

    function closeQuoteModal() {
        const modal = document.getElementById('quoteModal');
        if (modal) {
            modal.classList.remove('active');
            document.body.style.overflow = '';
        }
    }

    // Close modal on Escape key or outside click
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') closeQuoteModal();
    });
    const quoteModalElem = document.getElementById('quoteModal');
    if (quoteModalElem) {
        quoteModalElem.addEventListener('click', (e) => {
            if (e.target === quoteModalElem) closeQuoteModal();
        });
    }

    // FAQ Accordion Handler
    function toggleFaq(btn) {
        const faqItem = btn.closest('.faq-item');
        const answer = faqItem.querySelector('.faq-answer');
        const isActive = faqItem.classList.contains('active');

        // Close all other FAQs
        document.querySelectorAll('.faq-item').forEach(item => {
            item.classList.remove('active');
            const ans = item.querySelector('.faq-answer');
            if (ans) ans.style.maxHeight = null;
        });

        if (!isActive) {
            faqItem.classList.add('active');
            answer.style.maxHeight = answer.scrollHeight + 'px';
        }
    }

    // Unified Form Submission with AJAX & WhatsApp Redirect
    async function submitQuoteForm(event, formType) {
        event.preventDefault();
        const form = event.target;
        const statusDiv = formType === 'modal' ? document.getElementById('modalFormStatus') : document.getElementById('heroFormStatus');
        const submitBtn = form.querySelector('button[type="submit"]');

        if (statusDiv) {
            statusDiv.style.display = 'block';
            statusDiv.style.color = 'var(--primary-navy)';
            statusDiv.innerText = 'Processing your relocation estimate request...';
        }

        if (submitBtn) submitBtn.disabled = true;

        const formData = new FormData(form);

        try {
            const response = await fetch('new/submit.php', {
                method: 'POST',
                body: formData,
                headers: {
                    'X-Requested-With': 'XMLHttpRequest'
                }
            });

            const data = await response.json();

            if (response.ok && data.status === 'success') {
                if (statusDiv) {
                    statusDiv.style.color = '#15803D';
                    statusDiv.innerHTML = '<i class="fas fa-check-circle"></i> Details saved! Opening WhatsApp to connect with team...';
                }
                form.reset();
                setTimeout(() => {
                    if (data.whatsapp_url) {
                        window.open(data.whatsapp_url, '_blank');
                    }
                    if (formType === 'modal') closeQuoteModal();
                }, 1000);
            } else {
                throw new Error(data.message || 'Submission failed');
            }
        } catch (err) {
            // Fallback directly to client-side WhatsApp generation so inquiry is never lost
            const name = form.querySelector('[name="name"]').value;
            const phone = form.querySelector('[name="phone"]').value;
            const pickup = form.querySelector('[name="pickup"]').value;
            const drop = form.querySelector('[name="drop"]').value;
            const service = form.querySelector('[name="service"]')?.value || 'Relocation Service';

            const waText = encodeURIComponent(
                `🚚 *New Moving Quote Request - Annapurna Packers*\n\n` +
                `👤 *Name:* ${name}\n` +
                `📞 *Phone:* ${phone}\n` +
                `📦 *Service:* ${service}\n` +
                `📍 *Pickup:* ${pickup}\n` +
                `🏁 *Drop:* ${drop}`
            );

            const waUrl = `https://wa.me/918333031259?text=${waText}`;

            if (statusDiv) {
                statusDiv.style.color = '#15803D';
                statusDiv.innerHTML = '<i class="fas fa-check-circle"></i> Opening WhatsApp to confirm your booking...';
            }

            setTimeout(() => {
                window.open(waUrl, '_blank');
                if (formType === 'modal') closeQuoteModal();
            }, 800);
        } finally {
            if (submitBtn) submitBtn.disabled = false;
        }
    }
</script>